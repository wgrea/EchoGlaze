  <!-- Terms -->
  <dl class="space-y-6 text-sm">

    <div id="resonance">
      <dt class="font-bold text-slate-900">Resonance</dt>
      <dd class="text-slate-600">
        The emotional alignment between a user’s current energy level and the
        social friction of a destination. Core to EchoGlaze’s decision model.
      </dd>
    </div>

    <div id="friction">
      <dt class="font-bold text-slate-900">Social Friction</dt>
      <dd class="text-slate-600">
        A measure of density, pace, and cultural onboarding difficulty. Used to
        match destinations to user mood.
      </dd>
    </div>

    <div id="vibe">
      <dt class="font-bold text-slate-900">Vibe Matching</dt>
      <dd class="text-slate-600">
        The process of aligning a user’s emotional state with a city’s
        atmosphere. A complement to Social Friction.
      </dd>
    </div>

    <div id="visa">
      <dt class="font-bold text-slate-900">Visa Certainty</dt>
      <dd class="text-slate-600">
        The predictability and stability of visa options. A key differentiator
        from traditional travel apps.
      </dd>
    </div>

    <div id="utility">
      <dt class="font-bold text-slate-900">Utility UX</dt>
      <dd class="text-slate-600">
        A design philosophy focused on clarity, speed, and scannability—optimized
        for decision‑making rather than aesthetics alone.
      </dd>
    </div>

    <div id="glaze">
      <dt class="font-bold text-slate-900">Glaze Layer</dt>
      <dd class="text-slate-600">
        EchoGlaze’s visual identity: soft blurs, optimistic gradients, and
        Frutiger‑Aero‑inspired depth cues.
      </dd>
    </div>

    <div id="hierarchy">
      <dt class="font-bold text-slate-900">Modular Country Hierarchy</dt>
      <dd class="text-slate-600">
        A refactored data model where each country is a self‑contained module
        powering multiple UI views without duplication.
      </dd>
    </div>

  </dl>

