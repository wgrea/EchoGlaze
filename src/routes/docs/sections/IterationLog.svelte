  <!-- Pivot -->
  <div id="pivot" class="relative pl-8 border-l-2 border-blue-500 mb-12">
    <h4 class="font-bold text-slate-800">March 2026: The EchoGlaze Pivot</h4>
    <p class="text-xs text-slate-500">
      Full rebranding from EchoTrip. Removed price tracking due to data
      volatility; shifted focus to <strong>Visa Certainty</strong> and
      <strong>Social Friction</strong> as the primary decision drivers.
    </p>
  </div>

  <!-- Aesthetic + Value -->
  <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-12">

    <!-- Aesthetic -->
    <div id="aesthetic" class="bg-purple-50 p-4 rounded-xl border border-purple-100">
      <h4 class="text-purple-900 font-bold text-xs uppercase mb-2">Aesthetic Reception</h4>
      <p class="text-xs text-purple-800">
        Users noted the “Game-like” feel. This validated the
        <strong>Frutiger Aero</strong> intent—making utility feel optimistic and
        emotionally warm rather than clinical.
      </p>
    </div>

    <!-- Value -->
    <div id="value" class="bg-red-50 p-4 rounded-xl border border-red-100">
      <h4 class="text-red-900 font-bold text-xs uppercase mb-2">Value Validation</h4>
      <p class="text-xs text-red-800">
        “Visa confusion is a big pain point.” Users prioritized legal clarity
        over destination variety, confirming our
        <strong>Depth over Breadth</strong> strategy.
      </p>
    </div>

  </div>

  <!-- Florida Insight -->
  <div id="florida" class="bg-slate-50 p-4 rounded-xl border border-slate-200 mb-12">
    <h4 class="text-slate-900 font-bold text-xs uppercase mb-2">The “Florida” Insight (Scope)</h4>
    <p class="text-xs text-slate-600">
      User interest in domestic states (like Florida) highlighted a future
      expansion path. Current focus remains <strong>City-Level</strong>
      international hubs to maintain data integrity and avoid scope creep.
    </p>
